// Writes dist/.htaccess and dist/_astro/.htaccess for the Apache host behind zariacapital.es,
// translating dist/_headers and dist/_redirects (the Cloudflare Pages / Netlify format) so the
// production headers, CSP hashes included, stay in sync with every build.
// Run after `npm run build:production`: node scripts/build-htaccess.mjs
import { readFile, writeFile } from 'node:fs/promises';

const SITE = 'https://zariacapital.es';
const dist = new URL('../dist/', import.meta.url);

function parseHeaders(text) {
	const blocks = new Map();
	let current = null;
	for (const raw of text.split('\n')) {
		if (!raw.trim() || raw.trim().startsWith('#')) continue;
		if (!/^\s/.test(raw)) {
			current = raw.trim();
			blocks.set(current, []);
		} else if (current) {
			const i = raw.indexOf(':');
			blocks.get(current).push([raw.slice(0, i).trim(), raw.slice(i + 1).trim()]);
		}
	}
	return blocks;
}

const q = (v) => {
	if (v.includes('"')) throw new Error(`Header value contains a double quote: ${v}`);
	return `"${v}"`;
};

const headers = parseHeaders(await readFile(new URL('_headers', dist), 'utf8'));
const redirects = (await readFile(new URL('_redirects', dist), 'utf8'))
	.split('\n')
	.map((l) => l.trim())
	.filter((l) => l && !l.startsWith('#'))
	.map((l) => l.split(/\s+/));

const all = headers.get('/*') ?? [];
if (!all.some(([k]) => k === 'Content-Security-Policy')) throw new Error('No CSP in _headers');
if (all.some(([, v]) => v.includes('__CSP__'))) throw new Error('CSP placeholder was not replaced');

const toRegex = (from) => {
	const path = from.replace(/^\//, '');
	if (path.endsWith('/*')) return `^${path.slice(0, -2).replace(/[.]/g, '\\.')}(/.*)?$`;
	return `^${path.replace(/[.]/g, '\\.')}$`;
};

const redirectRules = redirects
	.map(([from, to, status = '301']) => `  RewriteRule ${toRegex(from)} ${to.startsWith('http') ? to : SITE + to} [R=${status},L]`)
	.join('\n');

const root = `# Generated by scripts/build-htaccess.mjs from dist/_headers and dist/_redirects. Do not edit by hand.
# The previous WordPress .htaccess is kept on the server as .htaccess-wordpress-original.
# No HTTPS redirect here on purpose: Cloudflare sits in front and handles HTTPS.

Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  # Old WordPress sitemap address -> new sitemap
  RewriteRule ^wp-sitemap\\.xml$ ${SITE}/sitemap.xml [R=301,L]
  # Redirects from public/_redirects (absolute, so they stay on https)
${redirectRules}
  # The old WordPress files are kept in this folder but switched off: nothing of theirs is served.
  RewriteRule ^(wp-admin|wp-includes|wp-content|_wordpress-old)(/.*)?$ - [R=404,L]
  RewriteRule \\.(php|phtml)$ - [R=404,L]
  RewriteRule ^(readme\\.html|license\\.txt|index\\.html_old|\\.php\\.ini|\\.htaccess-wordpress-original|\\.ftp-deploy-sync-state\\.json)$ - [R=404,L]
</IfModule>

<IfModule mod_headers.c>
${all.map(([k, v]) => `  Header always set ${k} ${q(v)}`).join('\n')}
  <FilesMatch "\\.(html|xml|webmanifest)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>

<IfModule mod_mime.c>
  AddType image/avif .avif
  AddType image/webp .webp
  AddType font/woff2 .woff2
  AddType application/manifest+json .webmanifest
</IfModule>
`;

const astro = headers.get('/_astro/*') ?? [['Cache-Control', 'public, max-age=31536000, immutable']];
const astroFile = `# Generated by scripts/build-htaccess.mjs. Hashed build files: safe to cache for a year.
<IfModule mod_headers.c>
${astro.map(([k, v]) => `  Header set ${k} ${q(v)}`).join('\n')}
</IfModule>
`;

await writeFile(new URL('.htaccess', dist), root);
await writeFile(new URL('_astro/.htaccess', dist), astroFile);
console.log(`Wrote dist/.htaccess (${all.length} headers, ${redirects.length} redirects) and dist/_astro/.htaccess`);

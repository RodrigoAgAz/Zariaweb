// Builds the route network for the "Where we work" map from the city points in map-geometry.json.
// Writes src/components/home/map-routes.json (path data for Reach.astro) and
// src/components/home/map-routes.css (per-route draw order, scroll ranges and light timing).
// Run: node scripts/map/gen-routes.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const geo = JSON.parse(readFileSync(new URL('scripts/map/map-geometry.json', root), 'utf8'));
const pts = geo.pts;

// [from, to, bend, side]. The light runs from -> to, so directions are mixed on purpose: the network
// carries traffic both ways. bend is the curve's depth as a fraction of the chord; side says which
// way it bows (up = north, down, left = west, right = east).
const ROUTES = [
	['abudhabi', 'madrid', 0.22, 'up'],
	['madrid', 'newyork', 0.2, 'up'],
	['washington', 'madrid', 0.16, 'up'],
	['abudhabi', 'newyork', 0.26, 'up'],
	['madrid', 'mexico', 0.2, 'up'],
	['bogota', 'madrid', 0.14, 'up'],
	['madrid', 'buenosaires', 0.12, 'down'],
	['lima', 'madrid', 0.08, 'down'],
	['abudhabi', 'buenosaires', 0.1, 'up'],
	['santiago', 'abudhabi', 0.16, 'down'],
	['abudhabi', 'bogota', 0.22, 'up'],
	['newyork', 'sanfrancisco', 0.18, 'up'],
	['sanfrancisco', 'mexico', 0.22, 'left'],
	['newyork', 'mexico', 0.16, 'right'],
	['mexico', 'bogota', 0.2, 'down'],
	['washington', 'bogota', 0.12, 'right'],
	['bogota', 'guayaquil', 0.12, 'left'],
	['guayaquil', 'lima', 0.12, 'left'],
	['lima', 'santiago', 0.14, 'left'],
	['santiago', 'buenosaires', 0.25, 'down'],
	['buenosaires', 'newyork', 0.14, 'right'],
];

const SPEED = 220; // map units per second for the travelling light
const TRAVEL = 0.7; // share of each cycle spent travelling; the rest is a pause

function arc(a, b, bend, side) {
	const [x1, y1] = pts[a];
	const [x2, y2] = pts[b];
	const dx = x2 - x1, dy = y2 - y1, d = Math.hypot(dx, dy);
	let nx = -dy / d, ny = dx / d; // one of the two normals
	const want = { up: [0, -1], down: [0, 1], left: [-1, 0], right: [1, 0] }[side];
	if (nx * want[0] + ny * want[1] < 0) (nx = -nx), (ny = -ny);
	const cx = (x1 + x2) / 2 + nx * d * bend, cy = (y1 + y2) / 2 + ny * d * bend;
	return [x1, y1, +cx.toFixed(1), +cy.toFixed(1), x2, y2];
}

function length([x1, y1, cx, cy, x2, y2]) {
	let L = 0, px = x1, py = y1;
	for (let i = 1; i <= 400; i++) {
		const t = i / 400;
		const x = (1 - t) ** 2 * x1 + 2 * (1 - t) * t * cx + t * t * x2;
		const y = (1 - t) ** 2 * y1 + 2 * (1 - t) * t * cy + t * t * y2;
		L += Math.hypot(x - px, y - py);
		px = x;
		py = y;
	}
	return +L.toFixed(1);
}

// A fixed, evenly spread order for the lights' first departures (golden-ratio sequence), so they
// start scattered across the map rather than in route order.
const start = (i) => +(3 + ((i * 0.618034) % 1) * 6).toFixed(2);

const routes = ROUTES.map(([from, to, bend, side], i) => {
	const c = arc(from, to, bend, side);
	return { i, from, to, office: from === 'abudhabi' && to === 'madrid', d: `M${c[0]} ${c[1]}Q${c[2]} ${c[3]} ${c[4]} ${c[5]}`, len: length(c) };
});

writeFileSync(new URL('src/components/home/map-routes.json', root), JSON.stringify(routes, null, '\t') + '\n');

const n = routes.length;
let css = `/* Generated by scripts/map/gen-routes.mjs; do not edit by hand. ${n} routes. */\n\n`;
css += '/* Time-based draw (browsers without scroll timelines): one route after another. */\n';
for (const r of routes) css += `.js .map.is-in .arc.zr${r.i} { animation-delay: ${(0.3 + r.i * 0.18).toFixed(2)}s; }\n`;
css += '\n/* Scroll-linked draw: every route is drawn before the map reaches the middle of the screen. */\n@supports (animation-timeline: view()) {\n';
for (const r of routes) {
	const from = Math.round(10 + (r.i / (n - 1)) * 80);
	const to = Math.round(28 + (r.i / (n - 1)) * 17);
	css += `\t.js .map .arc.zr${r.i} { animation-range: entry ${from}% cover ${to}% !important; }\n`;
}
css += '}\n\n/* Lights: --k sizes the light to the route (pathLength is 1); the cycle is timed to the length. */\n';
for (const r of routes) {
	const cycle = (r.len / SPEED / TRAVEL).toFixed(2);
	css += `.map-svg .pulses .zr${r.i} { --k: ${(1 / r.len).toFixed(6)}; animation-duration: ${cycle}s; animation-delay: ${start(r.i)}s; }\n`;
}
writeFileSync(new URL('src/components/home/map-routes.css', root), css);
console.log(`${n} routes written`);
